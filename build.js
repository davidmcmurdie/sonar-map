// Shared Google bootstrap. opts.noKey / opts.authFail are HTML/text shown in the map area.
function googleApp(opts) {
  return `<script>
(function () {
'use strict';
${core}

${ui}

${rd('adapter-google.js')}
${opts.extra || ''}

  var root = document.getElementById('svm-root');
  if (!root || root.getAttribute('data-svm-started')) return;
  root.setAttribute('data-svm-started', '1');
  var mapEl = root.querySelector('.svm-map');
  function msg(t) { mapEl.innerHTML = '<div class="svm-msg">' + SVMCore.escapeHtml(t) + '</div>'; }
  var key = window.SVM_GOOGLE_MAPS_API_KEY;
  if (!key || key === 'YOUR_API_' + 'KEY') {
    mapEl.innerHTML = '<div class="svm-msg">' + ${JSON.stringify(opts.noKeyHtml)} + '</div>';
    return;
  }
  // Called by Google if the key is rejected (wrong key, API not enabled, or this web address not allowed).
  window.gm_authFailure = function () {
    msg(${JSON.stringify(opts.authFail)});
  };
  function start() {
    Promise.all([google.maps.importLibrary('maps'), google.maps.importLibrary('marker')]).then(function () {
      var app = SVMApp(root, SVMGoogleAdapter(mapEl));
      ${opts.after || ''}
    }).catch(function (e) { msg('Google Maps failed to load: ' + e.message); });
  }
  if (window.google && google.maps && google.maps.importLibrary) { start(); return; }
  window.__svmGoogleReady = start;
  var s = document.createElement('script');
  s.src = 'https://maps.googleapis.com/maps/api/js?key=' + encodeURIComponent(key) +
    '&v=weekly&loading=async&callback=__svmGoogleReady';
  s.async = true;
  s.onerror = function () { msg('Could not reach Google Maps. Check the internet connection.'); };
  document.head.appendChild(s);
})();
</script>`;
}

